def _deterministic_ids():
    """Repository ids from a counter, so the facts sent to the generator (they
    carry booking/event ids) and therefore the replay keys are reproducible."""
    counter = itertools.count(1)
    return mock.patch('src.foundation.repository.uuid4', side_effect=lambda: uuid.UUID(int=next(counter)))


def document_text(doc):
    """Synthetic upload content. The injected parser reads only the marker."""
    lines = ['SYNTHETIC QA FIXTURE - not a real mail', f"fixture-document: {doc['key']}",
             f"gold-case: {doc.get('gold_case') or '-'}"]
    lines += [booking.get('raw_snippet') or '' for booking in doc['bookings']]
    return ('\n'.join(lines) + '\n').encode('utf-8')


def _fixture_parser(fixture):
    by_key = {doc['key']: doc['bookings'] for trip in fixture['trips'] for doc in trip['documents']}

    def parse(raw):
        match = re.search(r'fixture-document: (\S+)', raw)
        if not match or match.group(1) not in by_key:
            raise ValueError('fixture document marker not found')
        return copy.deepcopy(by_key[match.group(1)])
    return parse


