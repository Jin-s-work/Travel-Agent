def live_upper_bound(fixture, items, pricing: dict, *, answer_model=ANSWER_MODEL, embedding_model=EMBEDDING_MODEL) -> dict:
    """Worst case: every question embeds once and generates once at the output cap.

    Input is bounded by UTF-8 bytes (>= tokens for these texts) plus framing:
    system prompt + every booking of the item's trip serialised twice (facts
    JSON and the context header) + the question. Fixture documents are
    embedded once each.
    """
    from src.rag import SYSTEM_PROMPT
    chat_price = pricing['prices'].get(f'openai/{answer_model}')
    embed_price = pricing['prices'].get(f'openai/{embedding_model}')
    if chat_price is None or embed_price is None:
        raise ValueError(f'가격 파일에 openai/{answer_model} 또는 openai/{embedding_model} 이 없습니다.')
    chat_rates = {key: Decimal(str(value)) for key, value in chat_price['rates_per_million'].items()}
    embed_rate = Decimal(str(embed_price['rates_per_million']['input_tokens']))
    out_cap = int(chat_price['max_units']['output_tokens'])
    trips = {trip['key']: trip for trip in fixture['trips']}
    total = Decimal(0)
    for trip in fixture['trips']:
        for doc in trip['documents']:
            total += embed_rate * (len(json.dumps(doc['bookings'], ensure_ascii=False).encode('utf-8')) + 256)
    system = len(SYSTEM_PROMPT.encode('utf-8'))
    for item in items:
        trip = trips[item['trip']]
        bookings = [b for doc in trip['documents'] for b in doc['bookings']] + list(trip.get('manual_bookings') or [])
        facts_bytes = len(json.dumps(bookings, ensure_ascii=False).encode('utf-8')) * 2
        question = len(item['question'].encode('utf-8'))
        total += embed_rate * (question + 256)
        total += chat_rates['input_tokens'] * (system + facts_bytes + question + 512) + chat_rates['output_tokens'] * out_cap
    return {'answer_model': answer_model, 'embedding_model': embedding_model, 'questions': len(items),
            'usd_bound': float(round(total / 1_000_000, 6)),
            'assumption': 'worst case: one query embedding + one generation at the output cap per question; '
                          'input bound = UTF-8 bytes + framing; fixture mails embedded once'}


