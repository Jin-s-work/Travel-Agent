def floor_sweep(env, items, rows, candidates=FLOOR_CANDIDATES):
    """Refusal precision/recall of the similarity floor alone, per candidate.

    Only questions that reached semantic retrieval in the main run take part.
    Each is re-asked with `config.ANSWER_MIN_SIMILARITY` patched and a stub
    generator that returns '' (metered as a fake call), so a refusal here can
    only come from retrieval (`grounding == 'refused'`), not from a model.
    """
    from src import config
    reached = {row['id'] for row in rows if row['reached_semantic']}
    subset = [item for item in items if item['id'] in reached]
    similarity = {}
    for item in subset:
        trip = env.trips[item['trip']]
        user = item.get('user') or trip.owner
        with env.generations.reader(user, trip.id) as reader:
            hits = reader.query(hash_embed([item['question']])[0], top_k=5)
        similarity[item['id']] = round(max((hit['similarity'] for hit in hits), default=0.0), 4)
    original = config.ANSWER_MIN_SIMILARITY
    results = []
    try:
        for floor in candidates:
            config.ANSWER_MIN_SIMILARITY = floor
            refused_ids = set()
            for item in subset:
                response, error, _ms = ask(env, item, f"qa:sweep:{floor}:{item['id']}", generator=lambda *_: '')
                if error is None and response.get('grounding') == 'refused':
                    refused_ids.add(item['id'])
            unanswerable = {item['id'] for item in subset if not item['answerable']}
            true_refusals = refused_ids & unanswerable
            results.append({'floor': floor, 'questions': len(subset), 'unanswerable': len(unanswerable),
                            'refused': len(refused_ids), 'refused_unanswerable': len(true_refusals),
                            'refused_answerable': len(refused_ids - unanswerable),
                            'precision': _ratio(len(true_refusals), len(refused_ids)),
                            'recall': _ratio(len(true_refusals), len(unanswerable))})
    finally:
        config.ANSWER_MIN_SIMILARITY = original

    answerable = [similarity[item['id']] for item in subset if item['answerable']]
    unanswerable = [similarity[item['id']] for item in subset if not item['answerable']]
    return {'embedder': f'hash-{HASH_DIMENSION} (synthetic, not {EMBEDDING_MODEL})', 'current_default': original,
            'candidates': results, 'top_similarity': {'answerable': _spread(answerable), 'unanswerable': _spread(unanswerable)},
            'per_question_top_similarity': similarity,
            'note': 'synthetic: 해시 임베더 기준이라 실제 임베딩 하한값으로 쓰면 안 된다.'}


def _spread(values):
    values = sorted(values)
    return {'n': len(values), 'min': values[0] if values else None,
            'median': percentile(values, 0.5), 'max': values[-1] if values else None}


def floor_estimate(rows, embedder, candidates=FLOOR_CANDIDATES):
    """Similarity-floor candidates from the main run's own retrievals (no extra call).

    `top_similarity` is the best hit of the query the run actually made (live:
    the real embedding). For each candidate, "dropped" means every semantic hit
    is below the floor. That is the retrieval half of a floor refusal only: a
    trip's manual bookings stay eligible and a question refused at the current
    floor never reached generation, so this is an estimate, not a re-run.
    """
    reached = [row for row in rows if row['top_similarity'] is not None and not row.get('expected_error')]
    unanswerable = {row['id'] for row in reached if not row['answerable']}
    table = []
    for floor in candidates:
        dropped = {row['id'] for row in reached if row['top_similarity'] < floor}
        true_drops = dropped & unanswerable
        table.append({'floor': floor, 'questions': len(reached), 'unanswerable': len(unanswerable),
                      'dropped': len(dropped), 'dropped_unanswerable': len(true_drops),
                      'dropped_answerable': len(dropped - unanswerable),
                      'precision': _ratio(len(true_drops), len(dropped)),
                      'recall': _ratio(len(true_drops), len(unanswerable))})
    return {'embedder': embedder, 'candidates': table,
            'top_similarity': {'answerable': _spread([r['top_similarity'] for r in reached if r['answerable']]),
                               'unanswerable': _spread([r['top_similarity'] for r in reached if not r['answerable']])},
            'note': '본 실행의 검색 결과로 계산한 추정이다(추가 호출 0). "떨어짐" = 의미검색 결과가 전부 하한 아래. '
                    '수동 예약 우회와 생성 단계 거절은 반영하지 않는다.'}


