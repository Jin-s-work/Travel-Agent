def call_cost_micros(call):
    """One reservation's spend by Budget's rule: released 0, settled actual,
    anything else (reserved/sent/unknown/pending_reconciliation) estimated."""
    if call['state'] == 'released':
        return 0
    if call['state'] == 'settled':
        return int(call['actual_cost_micros'] or 0)
    return int(call['estimated_cost_micros'] or 0)


def reservation_spend(db):
    """All reservations so far: count, spend (Budget rule) and count per state."""
    with db.connect() as con:
        rows = [dict(row) for row in con.execute(
            'SELECT state, actual_cost_micros, estimated_cost_micros FROM usage_reservations').fetchall()]
    states = {}
    for row in rows:
        states[row['state']] = states.get(row['state'], 0) + 1
    return {'calls': len(rows), 'cost_micros': sum(call_cost_micros(row) for row in rows),
            'by_state': dict(sorted(states.items())),
            'unsettled': sum(row['state'] in UNSETTLED_STATES for row in rows)}


def _recording_reader(generations, sink):
    """Wrap `generations.reader` (instance attribute) so every semantic
    `query` of the main run records its hits' similarities under
    `sink['current']`. No extra embedding or provider call is made."""
    original = generations.reader

    @contextmanager
    def reader(user_id, trip_id):
        with original(user_id, trip_id) as inner:
            query = inner.query

            def recorded(embedding, *args, **kwargs):
                hits = query(embedding, *args, **kwargs)
                if sink.get('current') is not None:
                    sink.setdefault('hits', {}).setdefault(sink['current'], []).extend(
                        float(hit['similarity']) for hit in hits if hit.get('similarity') is not None)
                return hits
            inner.query = recorded
            yield inner
    generations.reader = reader
    return original


