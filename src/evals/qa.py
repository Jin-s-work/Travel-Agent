def _qa_replay_adapter(store, *, build=False):
    from src.llm.replay import ReplayAdapter, make_record, request_key
    from src.rag import ANSWER_PROMPT

    class QaReplayAdapter(ReplayAdapter):
        """Knows the question being asked (for labels) and, when building,
        writes the item's hand-made answer as the record of its request."""

        def __init__(self):
            super().__init__(store)
            self.current = None
            self.served = []      # (item id, request key, source, label)
            self.built = []       # item ids whose record was written now
            self.unrecorded = []  # item ids that reached generation without a replay spec

        def preflight(self, kind, kwargs):
            if build and kind == 'chat' and self.store.get(request_key(kwargs)) is None:
                spec = (self.current or {}).get('replay')
                if spec:
                    self.store.put(make_record(kwargs, text=spec['text'], source=spec['source'],
                                               label=f"{self.current['id']}:{spec['label']}",
                                               prompt=ANSWER_PROMPT.meta()))
                    self.built.append(self.current['id'])
                elif self.current:
                    self.unrecorded.append(self.current['id'])
            return super().preflight(kind, kwargs)

        def send(self, client, kind, kwargs):
            result = super().send(client, kind, kwargs)
            self.served.append(((self.current or {}).get('id'), request_key(kwargs),
                                result.value.get('source'), result.value.get('label')))
            return result

    return QaReplayAdapter()


