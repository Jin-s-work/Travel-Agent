def run(mode, *, fixture_path=FIXTURE_PATH, questions_path=QUESTIONS_PATH, replay_dir=DEFAULT_REPLAY_DIR,
        max_questions=None, build=False, live_policy=None, workdir=None, sweep=True):
    if mode not in MODES:
        raise ValueError(f'unknown mode: {mode}')
    if mode == 'live' and workdir is None:
        raise ValueError('live 평가는 원장·영수증을 남길 workdir 가 필요합니다 (임시 디렉터리 금지).')
    fixture = load_fixture(fixture_path)
    items = load_questions(questions_path)
    problems = validate_fixture(fixture) + validate_questions(items, fixture)
    if problems:
        raise ValueError('평가셋 검증 실패: ' + '; '.join(problems[:10]))
    if max_questions is not None:
        items = select_questions(items, max_questions)
    adapter, records = None, {}
    if mode == 'replay':
        from src.llm.replay import ReplayStore
        store = ReplayStore(replay_dir)
        if Path(replay_dir).is_dir():
            for record in store.records():
                records[record['source']] = records.get(record['source'], 0) + 1
        adapter = _qa_replay_adapter(store, build=build)
        policy = replay_policy_config()
    elif mode == 'local':
        policy = replay_policy_config()
    else:
        policy = live_policy
    embedder = None if mode == 'live' else hash_embed
    if workdir is not None:
        Path(workdir).mkdir(parents=True, exist_ok=True)
    holder = tempfile.TemporaryDirectory(prefix='qa-eval-') if workdir is None else nullcontext(workdir)
    from src.llm import adapter_scope
    rows, sweep_result = [], None
    with holder as directory, qa_environment(directory, fixture, policy, embedder=embedder) as env:
        env.settings.mail_analysis_mode = 'local' if mode == 'local' else 'auto'
        structured_only = env.operations.structured_only()
        if structured_only != (mode == 'local'):
            raise RuntimeError(f'{mode} 모드인데 structured_only={structured_only} 입니다.')
        sink = {}
        original_reader = _recording_reader(env.generations, sink)
        try:
            with (adapter_scope(adapter) if adapter is not None else nullcontext()):
                for item in items:
                    if adapter is not None:
                        adapter.current, before = item, len(adapter.served)
                    sink['current'] = item['id']
                    request_id = f"qa:{mode}:{item['id']}"
                    response, error, wall_ms = ask(env, item, request_id)
                    served = adapter.served[before:] if adapter is not None else []
                    row = score_item(env, item, mode, response, error, wall_ms, _calls_for(env, request_id), served,
                                     similarities=sink.get('hits', {}).get(item['id']))
                    if item['id'] in env.error_details:
                        row['error_detail'] = env.error_details[item['id']]
                    rows.append(row)
                if adapter is not None:
                    adapter.current = None
        finally:
            sink['current'] = None
            env.generations.reader = original_reader
        total_spend = reservation_spend(env.db)
        answer_calls = total_spend['calls'] - env.fixture_calls
        if mode == 'replay' and sweep and not build:
            sweep_result = floor_sweep(env, items, rows)
    metrics = aggregate(rows)
    metrics['answer_phase_reservations'] = answer_calls
    # Whole run spend by Budget's rule: fixture mails (embedding) + answers.
    metrics['fixture_cost_usd'] = round(env.fixture_spend['cost_micros'] / 1_000_000, 6)
    metrics['fixture_calls_by_state'] = env.fixture_spend['by_state']
    metrics['run_cost_usd_total'] = round(total_spend['cost_micros'] / 1_000_000, 6)
    metrics['run_unsettled_calls'] = total_spend['unsettled']
    warnings = []
    if total_spend['unsettled']:
        warnings.append(f"정산되지 않은 호출 {total_spend['unsettled']}건(reserved/sent/unknown/pending_reconciliation)"
                        ' — 비용은 Budget 규칙대로 예상 비용으로 넣었다. 공급자 사용량 화면과 대조할 것.')
    floor_from_run = floor_estimate(rows, f'hash-{HASH_DIMENSION} (synthetic, not {EMBEDDING_MODEL})'
                                    if mode != 'live' else f'{EMBEDDING_MODEL} (live)') if mode != 'local' else None
    result = {
        'suite': SUITE, 'mode': mode, 'synthetic': True, 'quality_claim': QUALITY_CLAIM[mode],
        'generated_at': datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        'fixture': _relative(fixture_path), 'questions': _relative(questions_path),
        # Content pins for the gate (gold.questions_sha256 / fixture_sha256): a weaker
        # expectation under the same question id changes these and fails.
        'questions_sha256': file_content_sha256(questions_path), 'fixture_sha256': file_content_sha256(fixture_path),
        'answer_model': ANSWER_MODEL if mode != 'local' else None,
        'path': 'search.answer basic (structured_only)' if mode == 'local'
                else 'search.answer AI path (hash embedder + rag.generate via ReplayAdapter)' if mode == 'replay'
                else 'search.answer AI path (live embeddings + generation, budget-capped)',
        'replay': {'dir': _relative(replay_dir), 'records_by_source': dict(sorted(records.items())),
                   'served_by_source': _served_counts(rows)} if mode == 'replay' else None,
        'warnings': warnings, 'metrics': metrics, 'floor_sweep': sweep_result, 'floor_estimate': floor_from_run,
        'workdir': _relative(workdir) if mode == 'live' else None,
        # Gate-compatible index: gate.check_gold reads metrics.cases + cases[].case_id
        # (question-set coverage), gate.check_known_gaps reads cases[].scenario_id + flags.
        'cases': [{'case_id': row['id'], 'scenario_id': row['id'], 'status': row['status'],
                   'verifier_false_fallback': row['verifier_false_fallback'],
                   'planted_fault_caught': row['planted_fault_caught'],
                   'injection_text_relay': row['injection_text_relay']} for row in rows],
        'items': rows,
    }
    if build and adapter is not None:
        result['build'] = {'written': adapter.built, 'reached_generation_without_spec': adapter.unrecorded}
    return result


def file_content_sha256(path):
    """Hash of a JSON file's normalized content (key order and whitespace do not matter)."""
    value = json.loads(Path(path).read_text(encoding='utf-8'))
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
                          .encode('utf-8')).hexdigest()


def _served_counts(rows):
    counts = {}
    for row in rows:
        for entry in row.get('replay') or []:
            counts[entry['source']] = counts.get(entry['source'], 0) + 1
    return dict(sorted(counts.items()))


def _fmt(value):
    return '—' if value is None else (f'{value:.4f}' if isinstance(value, float) else str(value))


