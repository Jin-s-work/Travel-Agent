_TOKEN = re.compile(r'\w+', re.UNICODE)


def _features(text):
    """Distinct features: word tokens (minus 1-char ASCII and bare numbers) and
    character bigrams of non-ASCII tokens, so Korean/Japanese partial words
    overlap ('체크인' ~ '체크인과'). Presence only: repeated JSON keys of the
    indexed booking text do not dominate."""
    features = set()
    for token in _TOKEN.findall(unicodedata.normalize('NFKC', str(text)).casefold()):
        if token.isascii() and (len(token) < 2 or token.isdigit()):
            continue
        features.add('w:' + token)
        if not token.isascii():
            features.update('c:' + token[index:index + 2] for index in range(len(token) - 1))
    return sorted(features)


def hash_embed(texts, dimension=HASH_DIMENSION):
    """Signed feature hashing, L2-normalised. Same text → same vector, any machine."""
    vectors = []
    for text in texts:
        vector = [0.0] * dimension
        for feature in _features(text):
            digest = hashlib.sha256(feature.encode('utf-8')).digest()
            index = int.from_bytes(digest[:4], 'big') % dimension
            vector[index] += 1.0 if digest[4] & 1 else -1.0
        norm = math.sqrt(sum(value * value for value in vector))
        if norm == 0:
            vector[0], norm = 1.0, 1.0
        vectors.append([round(value / norm, 6) for value in vector])
    return vectors


def cosine(left, right):
    return sum(a * b for a, b in zip(left, right))


