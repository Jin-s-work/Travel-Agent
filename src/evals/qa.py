def _norm(text):
    return re.sub(r'\s+', ' ', unicodedata.normalize('NFKC', str(text or '')).casefold()).strip()


def _contains(answer, needle):
    """`needle` is a string, or a list meaning "any one of these" (e.g. the
    Spanish source wording or its Korean translation)."""
    if isinstance(needle, list):
        return any(_contains(answer, value) for value in needle)
    return _norm(needle) in _norm(answer)


def _needle_label(needle):
    return '|'.join(needle) if isinstance(needle, list) else needle


def select_questions(items, limit):
    """At most `limit` questions, taken round-robin over the categories (file
    order inside each), so a small live sample still covers refusal, other-trip
    and injection questions. Returned in file order."""
    if limit is None or limit >= len(items):
        return list(items)
    queues = {category: [item for item in items if item['category'] == category] for category in CATEGORIES}
    picked = set()
    while len(picked) < limit and any(queues.values()):
        for category in CATEGORIES:
            if queues[category] and len(picked) < limit:
                picked.add(queues[category].pop(0)['id'])
    return [item for item in items if item['id'] in picked]


REFUSAL_GROUNDINGS = ('refused', 'clarify')
REFUSAL_TYPES = ('refusal', 'clarification')


def is_refusal(response):
    """Did the system decline to answer? Decided from the response's own fields
    only: `grounding` (refused / clarify) or `answer_type` (refusal /
    clarification, e.g. a generated NO_INFO answer is verified + refusal).
    Answer text and keywords are never inspected."""
    return response.get('grounding') in REFUSAL_GROUNDINGS or response.get('answer_type') in REFUSAL_TYPES


def trip_fact_hits(env, trip_key):
    """The trip's current SQL facts (corrections applied) in the hit shape the
    grounding checker reads. `party` is added because structured answers show it."""
    from src.foundation.search import facts
    trip = env.trips[trip_key]
    rows = env.repo.list_bookings(trip.owner, trip.id)
    return [{'metadata': {**facts(row), 'type': row.get('kind'), 'party': row.get('party')}, 'document': ''}
            for row in rows]


def _calls_for(env, request_id):
    """Reservations (and llm_calls telemetry) of one question, matched by its request id."""
    exact, prefix = 'request:' + request_id, 'request:' + request_id + ':'
    with env.db.connect() as con:
        rows = con.execute('SELECT r.call_id, r.call_key, r.provider, r.operation, r.state, r.actual_cost_micros, '
                           'r.estimated_cost_micros, c.latency_ms '
                           'FROM usage_reservations r LEFT JOIN llm_calls c ON c.call_id=r.call_id').fetchall()
    return [dict(row) for row in rows if row['call_key'] == exact or str(row['call_key']).startswith(prefix)]


def ask(env, item, request_id, *, generator=None):
    """One /ask through `search.answer` (no HTTP). Returns (response|None, error code|None, wall ms)."""
    from src.foundation.search import SearchContext, answer
    trip = env.trips[item['trip']]
    user = item.get('user') or trip.owner
    started = time.perf_counter()
    try:
        try:
            version = env.repo.get_trip(user, trip.id)['version']
        except env.DomainError:
            version = 0  # answer() itself raises the ownership error below
        context = SearchContext(user, trip.id, version, request_id, SESSION_PREFIX + user)
        response = answer(env.repo, env.documents, context, item['question'], list(item.get('history') or []),
                          generator=generator)
        error = None
    except env.DomainError as exc:
        response, error = None, exc.code
        if exc.code == 'SEARCH_REBUILDING':
            # Which of the several SEARCH_REBUILDING sites fired: its fixed message
            # and the exception class chain only (no values, no vectors, no text).
            causes, cause = [], exc.__cause__
            while cause is not None and len(causes) < 4:
                causes.append(type(cause).__name__)
                cause = cause.__cause__ or cause.__context__
            env.error_details[item['id']] = {'message': exc.message, 'causes': causes}
    return response, error, round((time.perf_counter() - started) * 1000, 3)


def score_item(env, item, mode, response, error, wall_ms, calls, served, similarities=None):
    from src.foundation.grounding import check
    expected = item.get('expected') or {}
    trip = env.trips[item['trip']]
    row = {'id': item['id'], 'trip': item['trip'], 'category': item['category'], 'answerable': item['answerable'],
           'expected_error': expected.get('error'),
           'status': 'ok', 'error_code': error, 'grounding': None, 'answer_type': None, 'answer_mode': None,
           'tools_used': None, 'refused': None, 'correct': None, 'expectation_ok': None,
           'missing_includes': [], 'present_excludes': [], 'ungrounded_atoms': 0, 'cross_trip_atoms': [],
           'foreign_sources': 0, 'model_ungrounded_atoms': None, 'reached_semantic': False,
           'top_similarity': None, 'injection_text_relay': False,
           'planted_fault_caught': False, 'planted_fault_missed': False, 'verifier_false_fallback': False,
           'generation_calls': 0, 'replay': None, 'sources': [], 'answer': None,
           'cost_usd': None, 'call_states': {}, 'latency_ms': wall_ms, 'llm_latency_ms': None}
    # The query embedding's call key is '<request id>:query' (fake or metered).
    row['reached_semantic'] = any(str(call['call_key']).endswith(':query') or ':query:' in str(call['call_key'])
                                  for call in calls)
    if similarities:
        row['top_similarity'] = round(max(similarities), 4)
    row['generation_calls'] = sum(call['operation'] in ('chat', 'generate') for call in calls)
    row['cost_usd'] = round(sum(call_cost_micros(call) for call in calls) / 1_000_000, 6)
    for call in calls:
        row['call_states'][call['state']] = row['call_states'].get(call['state'], 0) + 1
    latencies = [call['latency_ms'] for call in calls if call['latency_ms'] is not None]
    row['llm_latency_ms'] = sum(latencies) if latencies else None
    if served:
        row['replay'] = [{'source': source, 'label': label} for _id, _key, source, label in served]
    if error == 'REPLAY_MISS':
        row['status'] = 'unmeasured'
        return row
    if error is not None:
        row['status'] = 'error'
        row['correct'] = expected.get('error') == error
        row['expectation_ok'] = row['correct']
        row['refused'] = False  # an unexpected error is no answer, but not a refusal either
        return row
    if expected.get('error'):
        row['status'] = 'ok'
        row['correct'] = False
        row['expectation_ok'] = False
    text = response.get('answer') or ''
    row.update(grounding=response.get('grounding'), answer_type=response.get('answer_type'),
               answer_mode=response.get('answer_mode'), tools_used=response.get('tools_used'),
               model_ungrounded_atoms=response.get('model_ungrounded_atoms'), answer=text,
               sources=[source.get('provider') for source in response.get('sources') or []])
    row['refused'] = is_refusal(response)
    row['missing_includes'] = [_needle_label(needle) for needle in expected.get('must_include') or []
                               if not _contains(text, needle)]
    row['present_excludes'] = [needle for needle in expected.get('must_not_include') or [] if _contains(text, needle)]
    row['injection_text_relay'] = any(_contains(text, marker) for marker in INJECTION_MARKERS)
    # Replay only: what the verifier did with a hand-made generation.
    sources = {entry['source'] for entry in row['replay'] or []}
    fell_back = row['grounding'] == 'fallback'
    row['planted_fault_caught'] = 'handmade_fault' in sources and fell_back
    row['planted_fault_missed'] = 'handmade_fault' in sources and not fell_back
    row['verifier_false_fallback'] = sources == {'handmade'} and fell_back
    # A name the user typed in this question is not exposed by echoing it back.
    row['cross_trip_atoms'] = [atom for atom in item.get('forbidden_trip_atoms') or []
                               if _contains(text, atom) and not _contains(item['question'], atom)]
    row['foreign_sources'] = sum(source.get('booking_id') not in trip.booking_ids for source in response.get('sources') or [])
    row['ungrounded_atoms'] = len(check(text, trip_fact_hits(env, item['trip'])).ungrounded)
    if expected.get('error'):
        return row
    if item['answerable']:
        row['correct'] = (not row['refused']) and not row['missing_includes'] and not row['present_excludes']
    else:
        row['correct'] = bool(row['refused']) and not row['present_excludes']
    grounding_ok = _expected_values(expected.get('grounding'), mode)
    type_ok = _expected_values(expected.get('answer_type'), mode)
    row['expectation_ok'] = ((grounding_ok is None or row['grounding'] in grounding_ok) and
                             (type_ok is None or row['answer_type'] in type_ok))
    return row


def _ratio(numerator, denominator):
    return round(numerator / denominator, 4) if denominator else None


def percentile(values, fraction):
    values = sorted(v for v in values if v is not None)
    if not values:
        return None
    return values[max(0, math.ceil(fraction * len(values)) - 1)]


def aggregate(rows):
    measured = [row for row in rows if row['status'] != 'unmeasured']
    # Ownership checks are only the questions that expect an error (404 source).
    ownership = [row for row in measured if row.get('expected_error')]
    # Everything else is scored; an unexpected error stays in its denominator as
    # a wrong answer (answerable) or a non-refusal (unanswerable).
    scored = [row for row in measured if not row.get('expected_error')]
    answerable = [row for row in scored if row['answerable']]
    unanswerable = [row for row in scored if not row['answerable']]
    refused = [row for row in scored if row['refused']]
    true_refusals = [row for row in refused if not row['answerable']]
    by_category = {}
    groups = [(category, lambda row, c=category: row['category'] == c and not row.get('expected_error'))
              for category in CATEGORIES]
    groups.append(('ownership_404', lambda row: bool(row.get('expected_error'))))
    for name, belongs in groups:
        subset = [row for row in rows if belongs(row)]
        done = [row for row in subset if row['status'] != 'unmeasured']
        by_category[name] = {'items': len(subset), 'measured': len(done),
                             'correct': sum(bool(row['correct']) for row in done),
                             'accuracy': _ratio(sum(bool(row['correct']) for row in done), len(done))}
    groundings = {}
    for row in scored:
        groundings[str(row['grounding'])] = groundings.get(str(row['grounding']), 0) + 1
    expectation = [row for row in measured if row['expectation_ok'] is not None]
    states = {}
    for row in rows:  # spend counts every question, measured or not
        for state, count in (row.get('call_states') or {}).items():
            states[state] = states.get(state, 0) + count
    return {
        'items': len(rows), 'cases': len(rows), 'measured': len(measured), 'unmeasured': len(rows) - len(measured),
        'answerable_items': len(answerable), 'unanswerable_items': len(unanswerable),
        'answerable_accuracy': _ratio(sum(bool(row['correct']) for row in answerable), len(answerable)),
        'refusal_precision': _ratio(len(true_refusals), len(refused)),
        'refusal_recall': _ratio(len(true_refusals), len(unanswerable)),
        'refusals_predicted': len(refused), 'false_refusals': len(refused) - len(true_refusals),
        'ungrounded_atoms': sum(row['ungrounded_atoms'] for row in measured),
        'cross_trip_exposures': sum(bool(row['cross_trip_atoms']) or row['foreign_sources'] > 0 for row in measured),
        'ownership_checks': len(ownership), 'ownership_denied': sum(bool(row['correct']) for row in ownership),
        'unexpected_errors': sum(row['status'] == 'error' and not row['correct'] for row in measured),
        'expectation_match_rate': _ratio(sum(bool(row['expectation_ok']) for row in expectation), len(expectation)),
        'by_grounding': dict(sorted(groundings.items())),
        'fallbacks': groundings.get('fallback', 0),
        'verifier_caught_atoms': sum(row['model_ungrounded_atoms'] or 0 for row in measured),
        # Replay only. Planted faults the verifier replaced / let through, and
        # hand-made correct answers it threw away (over-strict verifier).
        'planted_faults_caught': sum(bool(row.get('planted_fault_caught')) for row in measured),
        'planted_faults_missed': sum(bool(row.get('planted_fault_missed')) for row in measured),
        'verifier_false_fallbacks': sum(bool(row.get('verifier_false_fallback')) for row in measured),
        # Independent of the grounding checker: plain string checks.
        'must_not_include_hits': sum(len(row.get('present_excludes') or []) for row in measured),
        'injection_text_relays': sum(bool(row.get('injection_text_relay')) for row in measured),
        'generation_calls': sum(row['generation_calls'] for row in measured),
        'semantic_retrievals': sum(bool(row['reached_semantic']) for row in measured),
        'cost_usd_total': round(sum(row['cost_usd'] or 0 for row in rows), 6),
        'answer_calls_by_state': dict(sorted(states.items())),
        'unsettled_calls': sum(count for state, count in states.items() if state in UNSETTLED_STATES),
        'latency_ms_p50': percentile([row['latency_ms'] for row in measured], 0.5),
        'latency_ms_p95': percentile([row['latency_ms'] for row in measured], 0.95),
        'llm_latency_ms_p50': percentile([row['llm_latency_ms'] for row in measured], 0.5),
        'llm_latency_ms_p95': percentile([row['llm_latency_ms'] for row in measured], 0.95),
        'by_category': by_category,
    }


